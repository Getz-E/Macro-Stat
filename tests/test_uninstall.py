"""uninstall.sh yalnızca MacroStat'ın kurduğu dosyaları kaldırmalıdır."""

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UNINSTALL = ROOT / "uninstall.sh"
COMMON = ROOT / "packaging" / "install-common.sh"
SHIPPED_ICON = ROOT / "assets" / "macrostat.svg"

MARKER = "X-MacroStat-Autogenerated=true\n"


def udev_rule_text():
    result = subprocess.run(
        ["bash", "-c", 'source "{}"; udev_rule_content'.format(COMMON)],
        capture_output=True, text=True, check=True)
    return result.stdout


class UninstallTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)
        self.home = self.tmp / "home"
        self.apps = self.home / ".local/share/applications"
        self.desktop = self.home / "Desktop"
        self.icon_dir = self.home / ".local/share/icons/hicolor/scalable/apps"
        self.rules = self.tmp / "99-macrostat.rules"
        self.profile = self.home / ".config/macrostat/profile.json"
        for path in (self.apps, self.desktop, self.icon_dir,
                     self.profile.parent):
            path.mkdir(parents=True)

    def tearDown(self):
        self._tmp.cleanup()

    def run_uninstall(self, *args, extra_env=None):
        env = os.environ.copy()
        env.update({
            "HOME": str(self.home),
            "USER_HOME": str(self.home),
            "USER": "tester",
            "MACROSTAT_APPS_DIR": str(self.apps),
            "MACROSTAT_DESKTOP_DIR": str(self.desktop),
            "MACROSTAT_ICON_DIR": str(self.icon_dir),
            "MACROSTAT_RULES_PATH": str(self.rules),
            "MACROSTAT_PROFILE_PATH": str(self.profile),
        })
        env.update(extra_env or {})
        return subprocess.run(["bash", str(UNINSTALL), *args],
                              capture_output=True, text=True, env=env)

    def write_ours(self):
        entry = "[Desktop Entry]\nName=MacroStat\nExec=\"x\"\n" + MARKER
        (self.apps / "macrostat.desktop").write_text(entry, encoding="utf-8")
        (self.desktop / "MacroStat.desktop").write_text(entry, encoding="utf-8")
        shutil.copy(SHIPPED_ICON, self.icon_dir / "macrostat.svg")
        self.rules.write_text(udev_rule_text(), encoding="utf-8")

    def test_removes_only_our_artifacts(self):
        self.write_ours()
        (self.apps / "other.desktop").write_text("Name=Other\n", encoding="utf-8")
        (self.icon_dir / "other.svg").write_text("<svg/>", encoding="utf-8")

        result = self.run_uninstall()

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse((self.apps / "macrostat.desktop").exists())
        self.assertFalse((self.desktop / "MacroStat.desktop").exists())
        self.assertFalse((self.icon_dir / "macrostat.svg").exists())
        self.assertFalse(self.rules.exists())
        self.assertTrue((self.apps / "other.desktop").exists())
        self.assertTrue((self.icon_dir / "other.svg").exists())

    def test_keeps_user_modified_files(self):
        entry = "[Desktop Entry]\nName=Benim\nExec=\"kendi\"\n"
        (self.apps / "macrostat.desktop").write_text(entry, encoding="utf-8")
        (self.desktop / "MacroStat.desktop").write_text(entry, encoding="utf-8")
        (self.icon_dir / "macrostat.svg").write_text(
            "<svg><!-- değiştirilmiş --></svg>", encoding="utf-8")
        self.rules.write_text('KERNEL=="uinput", MODE="0666"\n', encoding="utf-8")

        result = self.run_uninstall()

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual((self.apps / "macrostat.desktop").read_text(
            encoding="utf-8"), entry)
        self.assertEqual((self.desktop / "MacroStat.desktop").read_text(
            encoding="utf-8"), entry)
        self.assertIn("değiştirilmiş",
                      (self.icon_dir / "macrostat.svg").read_text(encoding="utf-8"))
        self.assertTrue(self.rules.exists())

    def test_profile_is_kept_unless_purge_requested(self):
        self.profile.write_text('{"macros": []}', encoding="utf-8")

        self.assertEqual(self.run_uninstall().returncode, 0)
        self.assertTrue(self.profile.exists())

        self.assertEqual(self.run_uninstall("--purge-profile").returncode, 0)
        self.assertFalse(self.profile.exists())

    def test_never_removes_system_packages(self):
        text = UNINSTALL.read_text(encoding="utf-8")
        for forbidden in ("pacman -R", "apt-get remove", "apt remove",
                          "dnf remove", "dnf erase"):
            self.assertNotIn(forbidden, text)

    def test_help(self):
        result = self.run_uninstall("--help")
        self.assertEqual(result.returncode, 0)
        self.assertIn("Usage", result.stdout)

    def test_privileged_commands_use_trusted_absolute_paths(self):
        text = UNINSTALL.read_text(encoding="utf-8")
        self.assertIn("run_root_tool rm -f", text)
        self.assertIn("trusted_executable udevadm", text)
        self.assertNotIn("run_privileged rm", text)
        self.assertNotIn("run_privileged udevadm", text)
        self.assertNotIn("command -v udevadm", text)

    def test_malicious_rm_earlier_in_path_is_not_executed(self):
        self.write_ours()
        marker = self.tmp / "malicious-rm-ran"
        bin_dir = self.tmp / "bin"
        bin_dir.mkdir()
        evil_rm = bin_dir / "rm"
        evil_rm.write_text(
            "#!/bin/sh\n: > '{}'\nexit 0\n".format(marker), encoding="utf-8")
        evil_rm.chmod(0o755)

        result = self.run_uninstall(extra_env={
            "PATH": "{}:{}".format(bin_dir, os.environ.get("PATH", "")),
        })

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(marker.exists(), "PATH'teki sahte rm çalıştırıldı")
        self.assertFalse((self.apps / "macrostat.desktop").exists())
        self.assertFalse((self.rules).exists())

    def test_missing_udevadm_does_not_break_uninstall(self):
        script = """
set -euo pipefail
source "{uninstall}"
trusted_executable() {{ return 1; }}
run_root_tool() {{ printf 'unexpected\\n'; return 1; }}
DEFAULT_RULES=/etc/udev/rules.d/99-macrostat.rules
reload_udev_rules "$DEFAULT_RULES"
printf 'completed\\n'
""".format(uninstall=UNINSTALL)
        env = os.environ.copy()
        env.update({
            "HOME": str(self.home),
            "USER_HOME": str(self.home),
            "USER": "tester",
            "MACROSTAT_APPS_DIR": str(self.apps),
            "MACROSTAT_DESKTOP_DIR": str(self.desktop),
            "MACROSTAT_ICON_DIR": str(self.icon_dir),
            "MACROSTAT_RULES_PATH": str(self.rules),
            "MACROSTAT_PROFILE_PATH": str(self.profile),
        })
        result = subprocess.run(
            ["bash", "-c", script], capture_output=True, text=True, env=env)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("completed", result.stdout)
        self.assertNotIn("unexpected", result.stdout)


if __name__ == "__main__":
    unittest.main()
