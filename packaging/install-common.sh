# MacroStat shared installation library.
# Distribution wrappers (install_*.sh) source this file and call main.
# The wrapper must define:
#   DISTRO_FAMILY  : arch | debian | fedora
#   DISTRO_LABEL   : name shown to the user (e.g. "Ubuntu 24.04+")
#   DISTRO_MIN_VERSION : minimum version (may be empty for Arch)
# ==============================================================================

INSTALL_COMMON_PATH="${BASH_SOURCE[0]}"

# quick-xml 0.41 (RUSTSEC-2026-0194/0195 düzeltmesi) Rust 1.79 ister.
RUST_MIN_VERSION="1.79"

# ---------------------------------------------------------------------------
# os-release parsing / distribution detection
# ---------------------------------------------------------------------------
os_release_file() {
    printf '%s\n' "${MACROSTAT_OS_RELEASE:-/etc/os-release}"
}

os_release_value() {
    local key="$1" file line value
    file="$(os_release_file)"
    [ -r "$file" ] || return 1
    line="$(grep -m1 -E "^${key}=" "$file" 2>/dev/null || true)"
    [ -n "$line" ] || return 1
    value="${line#*=}"
    value="${value#[\"\']}"
    value="${value%[\"\']}"
    printf '%s\n' "$value"
}

detect_family() {
    local id idlike
    id="$(os_release_value ID || true)"
    idlike="$(os_release_value ID_LIKE || true)"
    id="${id,,}"
    idlike="${idlike,,}"

    case "$id" in
        ubuntu) printf 'ubuntu\n'; return 0 ;;
        debian) printf 'debian\n'; return 0 ;;
        fedora) printf 'fedora\n'; return 0 ;;
        arch|cachyos|endeavouros|manjaro) printf 'arch\n'; return 0 ;;
    esac
    case " $idlike " in
        *" ubuntu "*) printf 'ubuntu\n'; return 0 ;;
        *" debian "*) printf 'debian\n'; return 0 ;;
        *" fedora "*) printf 'fedora\n'; return 0 ;;
        *" arch "*) printf 'arch\n'; return 0 ;;
    esac

    if [ -z "$id" ]; then
        printf '❌ Could not read /etc/os-release; distribution is not supported.\n' >&2
    else
        printf "❌ '%s' is not supported. Use Ubuntu 24.04+, Debian 13+, Fedora 41+, or Arch/CachyOS.\n" "$id" >&2
    fi
    return 1
}

# ---------------------------------------------------------------------------
# Version comparison (dotted numbers)
# ---------------------------------------------------------------------------
version_ge() {
    local current="$1" minimum="$2" i a b
    local -a cur min
    IFS=. read -r -a cur <<< "$current"
    IFS=. read -r -a min <<< "$minimum"
    for i in 0 1 2 3; do
        a="${cur[i]:-0}"; b="${min[i]:-0}"
        a="${a%%[!0-9]*}"; b="${b%%[!0-9]*}"
        a="${a:-0}"; b="${b:-0}"
        if [ "$((10#$a))" -gt "$((10#$b))" ]; then return 0; fi
        if [ "$((10#$a))" -lt "$((10#$b))" ]; then return 1; fi
    done
    return 0
}

current_distro_version() {
    os_release_value VERSION_ID || printf '0\n'
}

require_expected_distro() {
    local expected="${EXPECTED_DISTRO:-}" actual
    [ -n "$expected" ] || return 0
    actual="$(detect_family)" || exit 1
    if [ "$actual" != "$expected" ]; then
        printf '❌ This script is for %s, but %s was detected.\n' "$expected" "$actual" >&2
        printf '   Use the matching install_*.sh file or the install_all.sh router.\n' >&2
        exit 1
    fi
}

require_supported_distro() {
    local current="${DISTRO_MIN_VERSION:-}"
    if [ -z "$current" ]; then
        return 0
    fi
    local installed
    installed="$(current_distro_version)"
    if ! version_ge "$installed" "$current"; then
        printf '❌ %s is required, but %s was found.\n' "$DISTRO_LABEL" "$installed" >&2
        printf '   On unsupported older releases the PyQt6/Rust packages may be missing or outdated.\n' >&2
        exit 1
    fi
}

# ---------------------------------------------------------------------------
# Desktop Entry generation
# ---------------------------------------------------------------------------
desktop_quote() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="${s//\`/\\\`}"
    s="${s//\$/\\\$}"
    printf '"%s"' "$s"
}

render_desktop_entry() {
    local exec_path="$1" icon="${2:-macrostat}"
    cat <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=MacroStat
Comment=Low-latency hardware macro engine
Exec=$(desktop_quote "$exec_path")
Icon=$icon
Terminal=false
Categories=Utility;Game;
StartupWMClass=MacroStat
X-MacroStat-Autogenerated=true
EOF
}

desktop_dir_from_config() {
    local config="$1" value
    [ -r "$config" ] || return 1
    value="$(sed -n 's/^XDG_DESKTOP_DIR="\(.*\)"[[:space:]]*$/\1/p' "$config" | head -n1)"
    [ -n "$value" ] || return 1
    value="${value//\$HOME/$HOME}"
    printf '%s\n' "$value"
}

detect_desktop_dir() {
    local dir config
    if [ -n "${MACROSTAT_DESKTOP_DIR:-}" ]; then
        printf '%s\n' "$MACROSTAT_DESKTOP_DIR"
        return 0
    fi
    if command -v xdg-user-dir >/dev/null 2>&1; then
        dir="$(xdg-user-dir DESKTOP 2>/dev/null || true)"
        if [ -n "$dir" ] && [ "$dir" != "$HOME" ]; then
            printf '%s\n' "$dir"
            return 0
        fi
    fi
    config="${XDG_CONFIG_HOME:-$HOME/.config}/user-dirs.dirs"
    if dir="$(desktop_dir_from_config "$config")" && [ "$dir" != "$HOME" ]; then
        printf '%s\n' "$dir"
        return 0
    fi
    printf '%s\n' "$HOME/Desktop"
}

udev_rule_content() {
    printf '%s\n' \
        'KERNEL=="uinput", SUBSYSTEM=="misc", TAG+="uaccess", OPTIONS+="static_node=uinput", MODE="0660"' \
        'SUBSYSTEM=="input", KERNEL=="event*", TAG+="uaccess", MODE="0660"'
}

# Prefer the absolute path of the installed file over an icon name: the
# shortcut logo stays visible even when the theme cache is stale.
resolved_icon() {
    local fallback="${1:-macrostat}"
    if [ -n "${MACROSTAT_ICON_PATH:-}" ] && [ -e "${MACROSTAT_ICON_PATH}" ]; then
        printf '%s\n' "$MACROSTAT_ICON_PATH"
    else
        printf '%s\n' "$fallback"
    fi
}

install_menu_entry() {
    local exec_path="$1" icon
    icon="$(resolved_icon "${2:-macrostat}")"
    local home="${USER_HOME:-$HOME}"
    local apps_dir="${MACROSTAT_APPS_DIR:-$home/.local/share/applications}"
    mkdir -p "$apps_dir"
    render_desktop_entry "$exec_path" "$icon" > "$apps_dir/macrostat.desktop"
    chmod 644 "$apps_dir/macrostat.desktop"
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database "$apps_dir" >/dev/null 2>&1 || true
    fi
    printf '%s\n' "$apps_dir/macrostat.desktop"
}

# Installs the menu entry and desktop shortcut, preserving an existing user file.
install_desktop_shortcut() {
    local exec_path="$1" icon
    icon="$(resolved_icon "${2:-macrostat}")"
    local desktop_dir menu_file desktop_file
    desktop_dir="$(detect_desktop_dir)"
    menu_file="$(install_menu_entry "$exec_path" "$icon")"
    desktop_file="$desktop_dir/MacroStat.desktop"

    mkdir -p "$desktop_dir"
    if [ -e "$desktop_file" ] && ! grep -q '^X-MacroStat-Autogenerated=true$' "$desktop_file" 2>/dev/null; then
        printf "⚠️  %s belongs to the user; not overwritten.\n" "$desktop_file" >&2
    else
        render_desktop_entry "$exec_path" "$icon" > "$desktop_file"
        # Executable bit so it can be launched by double-click.
        chmod 755 "$desktop_file"
        # GNOME/Nautilus does not run untrusted .desktop files.
        if command -v gio >/dev/null 2>&1; then
            gio set "$desktop_file" metadata::trusted true >/dev/null 2>&1 || true
        fi
    fi

    printf '%s\n' "$menu_file"
}

# ---------------------------------------------------------------------------
# Package installation
# ---------------------------------------------------------------------------
run_privileged() {
    if [ "$(id -u)" -eq 0 ]; then
        "$@"
    elif command -v sudo >/dev/null 2>&1; then
        sudo "$@"
    else
        printf '❌ Root/sudo is required for this step: %s\n' "$*" >&2
        exit 1
    fi
}

# Runs the command as the target user (for file ownership while running as root).
run_as_user() {
    local user="$1"; shift
    if [ "$(id -un)" = "$user" ]; then
        "$@"
    elif command -v sudo >/dev/null 2>&1; then
        sudo -u "$user" "$@"
    else
        runuser -u "$user" -- "$@"
    fi
}

ensure_pyqt6_repo() {
    # On Ubuntu python3-pyqt6 is only in the 'universe' repository; a clean
    # server install may have universe disabled. On Debian the package is in main.
    if ! command -v apt-cache >/dev/null 2>&1; then
        return 0
    fi
    if apt-cache show python3-pyqt6 >/dev/null 2>&1; then
        return 0
    fi
    # Minimal installs with an empty package list: refresh the index first.
    run_privileged apt-get update
    if apt-cache show python3-pyqt6 >/dev/null 2>&1; then
        return 0
    fi
    printf '   enabling the universe repository...\n'
    run_privileged apt-get install -y software-properties-common
    run_privileged add-apt-repository -y universe
    run_privileged apt-get update
}

install_packages() {
    local -a packages
    case "$DISTRO_FAMILY" in
        arch)
            packages=(python python-pyqt6 rust cargo)
            run_privileged pacman -S --needed --noconfirm "${packages[@]}"
            ;;
        debian)
            if [ "${EXPECTED_DISTRO:-}" = "ubuntu" ]; then
                ensure_pyqt6_repo
            fi
            packages=(python3 python3-pyqt6 rustc cargo)
            run_privileged apt-get update
            run_privileged env DEBIAN_FRONTEND=noninteractive \
                apt-get install -y --no-install-recommends "${packages[@]}"
            ;;
        fedora)
            packages=(python3 python3-pyqt6 rust cargo)
            run_privileged dnf install -y "${packages[@]}"
            ;;
        *)
            printf '❌ Unknown package family: %s\n' "$DISTRO_FAMILY" >&2
            exit 1
            ;;
    esac
}

# Ubuntu 24.04'ün depo rustc'si 1.75'tir; universe deposundaki sürümlü
# `rustc-1.79` / `cargo-1.79` paketleri güvenli quick-xml için gereken tabanı
# sağlar. Binler /usr/lib/rust-1.79/bin altında gelir.
install_versioned_rust() {
    local version="$RUST_MIN_VERSION"
    if [ "${MACROSTAT_SKIP_PACKAGES:-0}" -eq 1 ]; then
        return 1
    fi
    if [ "$DISTRO_FAMILY" != debian ] || ! command -v apt-cache >/dev/null 2>&1; then
        return 1
    fi
    if ! apt-cache show "rustc-$version" >/dev/null 2>&1 ||
       ! apt-cache show "cargo-$version" >/dev/null 2>&1; then
        return 1
    fi
    printf '   Installing rustc/cargo %s from the distribution...\n' "$version"
    run_privileged env DEBIAN_FRONTEND=noninteractive \
        apt-get install -y --no-install-recommends \
        "rustc-$version" "cargo-$version" || return 1
    if [ -d "/usr/lib/rust-$version/bin" ]; then
        PATH="/usr/lib/rust-$version/bin:$PATH"
        export PATH
    fi
    return 0
}

require_rust() {
    local min="$RUST_MIN_VERSION" version=""
    if command -v cargo >/dev/null 2>&1; then
        version="$(cargo --version 2>/dev/null | awk '{print $2}')"
    fi
    if ! version_ge "${version:-0}" "$min" && install_versioned_rust; then
        version="$(cargo --version 2>/dev/null | awk '{print $2}')"
    fi
    if [ -z "$version" ]; then
        printf '❌ cargo not found. Check the installation packages.\n' >&2
        exit 1
    fi
    if ! version_ge "${version:-0}" "$min"; then
        printf '❌ Rust %s or newer is required; found: %s\n' "$min" "$version" >&2
        exit 1
    fi
}

# ---------------------------------------------------------------------------
# Main flow
# ---------------------------------------------------------------------------
main() {
    local no_desktop=0 skip_packages=0
    while [ $# -gt 0 ]; do
        case "$1" in
            --no-desktop-shortcut) no_desktop=1 ;;
            --skip-packages) skip_packages=1 ;;
            -h|--help)
                printf 'Usage: %s [--skip-packages] [--no-desktop-shortcut]\n' "$0"
                return 0
                ;;
            *) printf "❌ Unknown option: %s\n" "$1" >&2; return 1 ;;
        esac
        shift
    done

    local dir
    dir="$(cd "$(dirname "$0")" >/dev/null 2>&1 && pwd)"
    cd "$dir"

    printf '🚀 MacroStat installation — %s\n' "${DISTRO_LABEL:-$DISTRO_FAMILY}"
    require_expected_distro
    require_supported_distro

    printf '📁 Verifying project files...\n'
    local f
    for f in Cargo.toml src/main.rs src/kwin_input.rs protocols/fake-input.xml \
             gui.py assets/default_profile.json start-macrostat.sh \
             macrostat/__init__.py macrostat/app.py macrostat/common.py \
             macrostat/core.py macrostat/editor.py macrostat/i18n.py \
             macrostat/kwin.py macrostat/logpanel.py macrostat/macros.py \
             macrostat/nav.py macrostat/onboarding.py macrostat/recorder.py \
             macrostat/sanitize.py macrostat/settings.py macrostat/system.py \
             macrostat/theme.py macrostat/transfer.py macrostat/widgets.py \
             assets/macrostat.svg; do
        if [ ! -f "$f" ]; then
            printf '❌ Missing file: %s\n' "$f" >&2
            exit 1
        fi
    done

    MACROSTAT_SKIP_PACKAGES="$skip_packages"
    export MACROSTAT_SKIP_PACKAGES
    if [ "$skip_packages" -eq 0 ]; then
        printf '📦 Installing system packages...\n'
        install_packages
    fi
    require_rust

    printf '⚙️  Building the Rust macro engine (release)...\n'
    cargo build --release --locked
    install -m 755 target/release/macrostat-daemon ./macrostat-daemon
    chmod +x ./start-macrostat.sh

    printf '🛡️  Installing the udev hardware permission rule...\n'
    local target_user="${SUDO_USER:-${USER:-$(id -un)}}"
    if ! [[ "$target_user" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,31}$ ]]; then
        printf "❌ Invalid user name: '%s'\n" "$target_user" >&2
        exit 1
    fi
    run_privileged modprobe uinput 2>/dev/null || true
    # Grant only the session owner (uaccess) instead of MODE 0666 or the broad 'input' group.
    udev_rule_content |
        run_privileged tee /etc/udev/rules.d/99-macrostat.rules >/dev/null
    run_privileged udevadm control --reload-rules
    run_privileged udevadm trigger

    local user_home
    user_home="$(getent passwd "$target_user" 2>/dev/null | awk -F: '{print $6}')"
    [ -n "$user_home" ] || user_home="$HOME"
    local icon_dir="$user_home/.local/share/icons/hicolor/scalable/apps"
    local exec_path="$dir/start-macrostat.sh"

    printf '🖥️  Installing the menu entry...\n'
    run_as_user "$target_user" mkdir -p "$icon_dir"
    run_as_user "$target_user" install -m 644 assets/macrostat.svg \
        "$icon_dir/macrostat.svg"
    # Menu entry first; install the desktop shortcut too unless disabled.
    if [ "$no_desktop" -eq 0 ]; then
        run_as_user "$target_user" env HOME="$user_home" USER_HOME="$user_home" \
            MACROSTAT_ICON_PATH="$icon_dir/macrostat.svg" \
            bash -c 'source "$1"; install_desktop_shortcut "$2" macrostat >/dev/null' \
            _ "$INSTALL_COMMON_PATH" "$exec_path"
        printf '   Desktop shortcut: %s/MacroStat.desktop\n' \
            "$(HOME="$user_home" USER_HOME="$user_home" detect_desktop_dir)"
    else
        run_as_user "$target_user" env HOME="$user_home" USER_HOME="$user_home" \
            MACROSTAT_ICON_PATH="$icon_dir/macrostat.svg" \
            bash -c 'source "$1"; install_menu_entry "$2" macrostat >/dev/null' \
            _ "$INSTALL_COMMON_PATH" "$exec_path"
    fi

    printf '✅ Installation completed successfully.\n'
    printf '   To start the interface: %s\n' "$exec_path"
    printf '   (On GNOME, desktop icons may be hidden by default; open the app from the menu.)\n'
}

# Run the main flow when executed directly (not sourced).
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    set -euo pipefail
    main "$@"
fi
